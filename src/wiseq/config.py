"""Runtime configuration.

All secrets arrive through environment variables (or .env). Nothing in this
module hardcodes a credential, and no credential is ever written to a log or a
prompt -- the review/price agents produce *drafts* for a human to send.
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()


def _env(name: str, default: str | None = None) -> str | None:
    v = os.getenv(name)
    return v if v not in (None, "") else default


def _env_int(name: str, default: int) -> int:
    try:
        return int(os.getenv(name, "") or default)
    except ValueError:
        return default


# Discount values that are known NOT to be a verified WiseQ rule.
# 0  -- the placeholder default.
# 15 -- the legacy demonstration value, invented by us, never sourced.
# Both stay flagged even if they are explicitly configured.
_UNVERIFIED_DISCOUNTS = (0.0, 15.0)


@dataclass(frozen=True)
class Settings:
    # --- storage -------------------------------------------------------
    # DSN is either postgres:// (Supabase) or sqlite:/// (local dev/test).
    # Accepts WISEQ_DATABASE_URL (canonical) or WISEQ_DB_URL (alias).
    database_url: str = field(default_factory=lambda: _env(
        "WISEQ_DATABASE_URL") or _env("WISEQ_DB_URL") or "sqlite:///./wiseq.db")

    # --- mail ----------------------------------------------------------
    # Every message generated by this system is delivered to this mailbox.
    # Dummy sender identities are used so no real customer is contacted.
    test_recipient: str = field(default_factory=lambda: _env(
        "WISEQ_TEST_RECIPIENT", "weissvanderpol@gmail.com"))
    test_sender: str = field(default_factory=lambda: _env(
        "WISEQ_TEST_SENDER", "wiseq-agent@example.invalid"))
    smtp_host: str = field(default_factory=lambda: _env("SMTP_HOST", "localhost"))
    smtp_port: int = field(default_factory=lambda: _env_int("SMTP_PORT", 1025))

    # --- business constants --------------------------------------------
    # school_discount_pct: DEFAULTED PLACEHOLDER, NOT A VERIFIED RULE.
    #
    # The live WiseQ site publishes *staffelprijzen* (volume tiers) whose
    # prices appear only after business registration. It does not publish a
    # flat school discount, and no percentage appears in the client's
    # operating manual or in Rob's 2026-10-28 transcript. The only 10-15%
    # figures on WiseQ pages are the attrition allowance for shared
    # headsets, which is a sizing input, not a discount.
    #
    # Those tier prices live inside WiseQ's own Shopify app ("Sami B2B
    # Wholesale Pricing", embedded on the B2B page as
    # {SamitaWSRegistrationForm:...}), so they are not in the public
    # catalogue, not in the repository, and not in the UCP/MCP feed. They
    # cannot be synced; Rob has to export them.
    #
    # The default is therefore 0 -- an unverified rule must never put a
    # number into a real quotation. Rob sets the real value (or 0) via
    # WISEQ_SCHOOL_DISCOUNT_PCT once the staffel export exists.
    school_discount_pct: float = field(default_factory=lambda: float(
        _env("WISEQ_SCHOOL_DISCOUNT_PCT", "0")))
    # True when the discount above is still an UNVERIFIED value.
    #
    # This is deliberately value-based rather than env-presence-based.
    # An earlier version keyed on "is the env var set?", which meant the
    # documented setup (`cp .env.example .env`, and the Compose default)
    # silently cleared the flag and promoted an invented percentage to a
    # confirmed WiseQ rule.
    #
    # A value is considered CONFIRMED only when
    #   - it is not one of the known-unverified values (0 and the legacy
    #     demonstration 15), and
    #   - the operator explicitly confirms it with
    #     WISEQ_SCHOOL_DISCOUNT_CONFIRMED=true.
    #
    # The explicit confirmation is what makes a staffel-derived value
    # auditable: it says "Rob supplied this", not "someone typed a number
    # into an env file".
    school_discount_is_placeholder: bool = field(default_factory=lambda:
        float(_env("WISEQ_SCHOOL_DISCOUNT_PCT", "0")) in _UNVERIFIED_DISCOUNTS
        or _env("WISEQ_SCHOOL_DISCOUNT_CONFIRMED", "").strip().lower()
        not in ("1", "true", "yes"))
    review_invitation_delay_days: int = field(default_factory=lambda: _env_int(
        "WISEQ_REVIEW_DELAY_DAYS", 7))
    strike_escalation_threshold: int = field(default_factory=lambda: _env_int(
        "WISEQ_STRIKE_ESCALATION", 3))
    auto_price_change_enabled: bool = False   # detect + recommend only
    review_send_enabled: bool = False         # draft only; human sends
    # Stock-based price raise: the manual says FiveX raises the price when
    # stock is 10 units or lower, and hedges the size ("ik geloof dat die
    # prijsstijging 10% is").  10 is therefore a PLACEHOLDER until Rob
    # confirms the real percentage -- same treatment as the school
    # discount.  Set WISEQ_STOCK_PRICE_RAISE_PCT to the confirmed value.
    stock_price_raise_pct: float = field(default_factory=lambda: float(
        _env("WISEQ_STOCK_PRICE_RAISE_PCT", "10")))
    stock_price_raise_is_placeholder: bool = field(default_factory=lambda:
        float(_env("WISEQ_STOCK_PRICE_RAISE_PCT", "10")) in (0.0, 10.0))

    # --- paths ---------------------------------------------------------
    # Root of the client data repository (the folder that contains `data/`).
    # Accepts either WISEQ_REPO_DIR or the older WISEQ_REPO_DATA_DIR name.
    repo_dir: Path | None = field(default_factory=lambda: (
        Path(_env("WISEQ_REPO_DIR") or _env("WISEQ_REPO_DATA_DIR"))
        if (_env("WISEQ_REPO_DIR") or _env("WISEQ_REPO_DATA_DIR")) else None))

    @property
    def is_sqlite(self) -> bool:
        return self.database_url.startswith("sqlite")

    @property
    def safe_recipients(self) -> list[str]:
        return [self.test_recipient]


_settings: Settings | None = None


def get_settings() -> Settings:
    global _settings
    if _settings is None:
        _settings = Settings()
    return _settings
