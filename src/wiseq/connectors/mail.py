"""Mail dispatcher.

Hard rule for this build: nothing leaves the machine except to the configured
test mailbox (``WISEQ_TEST_RECIPIENT``, default weissvanderpol@gmail.com).
Every outbound message is addressed to that mailbox, the sender is a dummy
``.invalid`` domain, and the real customer address is kept in the body as a
recipient reference so nothing is actually delivered to a third party.
"""
from __future__ import annotations

import smtplib
from dataclasses import dataclass
from email.message import EmailMessage

from ..agents.base import audit
from ..db.db import Database, new_id


@dataclass
class OutboundMail:
    to: str                 # real-world recipient (kept as reference only)
    subject: str
    body: str
    category: str = "general"


class MailDispatcher:
    """Collects outbound mail and (optionally) delivers it to the test inbox."""

    def __init__(self, db: Database, host: str = "localhost", port: int = 1025,
                 test_recipient: str = "weissvanderpol@gmail.com",
                 test_sender: str = "wiseq-agent@example.invalid"):
        self.db = db
        self.host = host
        self.port = port
        self.test_recipient = test_recipient
        self.test_sender = test_sender

    def send(self, mail: OutboundMail) -> dict:
        msg = EmailMessage()
        msg["From"] = self.test_sender
        msg["To"] = self.test_recipient          # always the test mailbox
        msg["Subject"] = f"[WiseQ-test] {mail.subject}"
        separator = "-" * 60
        footer = [
            separator,
            "intended recipient (reference only, NOT delivered): " + str(mail.to),
            "category: " + str(mail.category),
            "generated by: WiseQ Hermes agent",
        ]
        content = "\n".join([mail.body, "", *footer])
        msg.set_content(content)

        delivered = False
        error = None
        try:
            with smtplib.SMTP(self.host, self.port, timeout=10) as smtp:
                smtp.send_message(msg)
            delivered = True
        except Exception as exc:                       # noqa: BLE001
            error = str(exc)

        mail_id = new_id()
        self.db.execute(
            """INSERT INTO outbox (outbox_id, sent_to, intended_to, subject,
                                   body, category, delivered, error)
               VALUES (?,?,?,?,?,?,?,?)""",
            (mail_id, self.test_recipient, str(mail.to), mail.subject,
             content, mail.category, 1 if delivered else 0, error))
        self.db.execute(
            """INSERT INTO audit_log (audit_id, actor, action, entity_type, entity_id,
                                      detail, requires_human)
               VALUES (?,?,?,?,?,?,?)""",
            (mail_id, "mail_dispatcher", "mail_queued", "mail", mail_id,
             f"{mail.subject} -> {mail.to} (delivered_to_test={delivered})", 0))
        return {"id": mail_id, "delivered": delivered, "error": error,
                "sent_to": self.test_recipient}

    def send_batch(self, mails: list[OutboundMail]) -> dict:
        results = [self.send(m) for m in mails]
        return {"count": len(results),
                "delivered": sum(1 for r in results if r["delivered"]),
                "failed": sum(1 for r in results if not r["delivered"])}
